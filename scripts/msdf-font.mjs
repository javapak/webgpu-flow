// Packs an MSDF font atlas (BMFont JSON and its PNG, as msdf-bmfont-xml writes them)
// into a TypeScript module the label renderer imports, so the atlas ships inside the
// bundle: no fetch, nothing for a host's content security policy to allow.
//
// Regenerating src/assets/fonts/interMsdf.ts (Inter from github.com/google/fonts, ofl/inter):
//
//   npx -p msdf-bmfont-xml@2.8.0 msdf-bmfont -f json -s 36 -r 5 -p 2 -m 1024,1024 --pot \
//       -i charset.txt -o out/inter "Inter[opsz,wght].ttf"
//   node scripts/msdf-font.mjs out/Inter.json out/inter.png src/assets/fonts/interMsdf.ts Inter
//
// charset.txt: printable ASCII, Latin-1, Latin Extended-A, and the punctuation and
// symbols labels use (« » – — ‘ ’ “ ” • … → ⇒ ≤ ≥ ≠ × ÷ and so on). Text with other
// characters falls back to the canvas atlas.
import { readFileSync, writeFileSync } from 'node:fs';

const [jsonPath, pngPath, outPath, name = 'Inter'] = process.argv.slice(2);
if (!outPath) {
  console.error('usage: node scripts/msdf-font.mjs <font.json> <atlas.png> <out.ts> [name]');
  process.exit(1);
}

const font = JSON.parse(readFileSync(jsonPath, 'utf8'));
if (font.pages.length !== 1) throw new Error('expected a single-page atlas; raise the texture size');
if (font.distanceField?.fieldType !== 'msdf') throw new Error('expected an msdf atlas');

const glyphs = font.chars.map(c => [c.id, c.x, c.y, c.width, c.height, c.xoffset, c.yoffset, c.xadvance]);
const kernings = font.kernings.map(k => [k.first, k.second, k.amount]);
const png = readFileSync(pngPath).toString('base64');

const constName = `${name.toUpperCase().replace(/\W+/g, '_')}_MSDF`;
writeFileSync(outPath, `// Generated by scripts/msdf-font.mjs from ${font.info.face}; do not edit.
// The font is licensed under the SIL Open Font License 1.1: see ${name}-OFL.txt.
import type { MsdfFontData } from '../../renderers/MsdfFont';

export const ${constName}: MsdfFontData = {
  name: ${JSON.stringify(name)},
  size: ${font.info.size},
  lineHeight: ${font.common.lineHeight},
  base: ${font.common.base},
  distanceRange: ${font.distanceField.distanceRange},
  width: ${font.common.scaleW},
  height: ${font.common.scaleH},
  // [code point, x, y, width, height, xoffset, yoffset, xadvance], in atlas pixels
  glyphs: ${JSON.stringify(glyphs)},
  // [first, second, amount]
  kernings: ${JSON.stringify(kernings)},
  png: '${png}',
};
`);
console.log(`${outPath}: ${glyphs.length} glyphs, ${kernings.length} kerning pairs, ${Math.round(png.length / 1024)} KB of PNG`);
